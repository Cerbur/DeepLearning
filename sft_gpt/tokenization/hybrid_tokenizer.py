"""Lossless character/UTF-8-byte tokenizer for everyday multilingual text."""

from collections import Counter
import operator

from ..config import DEFAULT_TEXT_VOCAB
from .serialization import load_json, save_json_atomic, validate_tokenizer_spec


_SPECIAL_TOKENS = ("<BOS>", "<EOS>", "<UNK>", "<PAD>")
_BASE_TOKENS = list(_SPECIAL_TOKENS) + [f"<0x{byte:02X}>" for byte in range(256)]


class HybridTokenizer:
    """Use learned non-ASCII characters, with lossless UTF-8 byte fallback.

    IDs 0..3 are BOS/EOS/UNK/PAD; IDs 4..259 are the 256 byte values.
    Training selects characters by descending frequency (Unicode tie-break), then
    assigns the selected characters IDs in Unicode sort order. Loading never
    sorts or rebuilds. Input is not normalized or parsed for special-token text.
    """

    def __init__(self, tokens):
        self._validate_tokens(tokens)
        self.tokens = list(tokens)
        self.token_ids = {token: i for i, token in enumerate(self.tokens)}
        self.bos, self.eos, self.unk, self.pad = 0, 1, 2, 3

    @staticmethod
    def _validate_tokens(tokens):
        if not isinstance(tokens, list):
            raise ValueError("tokens must be an ordered JSON array")
        if any(not isinstance(token, str) for token in tokens):
            raise ValueError("every token must be a string")
        if tokens[:260] != _BASE_TOKENS:
            raise ValueError("the first 260 tokens must be fixed special and byte tokens")
        if len(set(tokens)) != len(tokens):
            raise ValueError("duplicate tokens are not allowed")
        for token in tokens[260:]:
            if len(token) != 1 or ord(token) < 128 or 0xD800 <= ord(token) <= 0xDFFF:
                raise ValueError("learned tokens must be non-ASCII Unicode scalar characters")

    @classmethod
    def build(cls, texts, min_freq=2, max_vocab_size=8192):
        """Count training texts only; max_vocab_size includes the 260 base IDs.

        Pass None for an unlimited vocabulary. ASCII always uses byte IDs.
        Only the supplied iterable is consumed; no validation/test data is read.
        """
        if type(min_freq) is not int or min_freq < 1:
            raise ValueError("min_freq must be a positive integer")
        if max_vocab_size is not None and (
            type(max_vocab_size) is not int or max_vocab_size < 260
        ):
            raise ValueError("max_vocab_size must be None or an integer >= 260")
        counts = Counter()
        for text in texts:
            if not isinstance(text, str):
                raise TypeError("training texts must be strings")
            text.encode("utf-8")  # Reject lone surrogates, which are not Unicode scalars.
            counts.update(text)
        chars = [char for char, count in counts.items()
                 if count >= min_freq and ord(char) >= 128]
        chars.sort(key=lambda char: (-counts[char], char))
        if max_vocab_size is not None:
            chars = chars[:max_vocab_size - 260]
        return cls(_BASE_TOKENS + sorted(chars))

    def encode(self, text, special_tokens=True):
        """Encode characters literally; special_tokens adds only outer BOS/EOS."""
        if not isinstance(text, str):
            raise TypeError("text must be a string")
        ids = []
        for char in text:
            learned_id = self.token_ids.get(char)
            if learned_id is not None:
                ids.append(learned_id)
            else:
                ids.extend(4 + byte for byte in char.encode("utf-8"))
        return [self.bos] + ids + [self.eos] if special_tokens else ids

    def _checked_id(self, value):
        try:
            token_id = operator.index(value)
        except TypeError as error:
            raise ValueError("token IDs must be integers") from error
        if isinstance(value, bool) or not 0 <= token_id < len(self.tokens):
            raise ValueError("token ID outside vocabulary")
        return token_id

    def decode(self, ids):
        """Decode adjacent byte IDs together; malformed generated bytes use U+FFFD."""
        parts = []
        pending = bytearray()
        for value in ids:
            token_id = self._checked_id(value)
            if token_id in (self.bos, self.eos, self.pad):
                continue
            if 4 <= token_id < 260:
                pending.append(token_id - 4)
                continue
            if pending:
                parts.append(pending.decode("utf-8", errors="replace"))
                pending.clear()
            parts.append(self.tokens[token_id])
        if pending:
            parts.append(pending.decode("utf-8", errors="replace"))
        return "".join(parts)

    def to_dict(self):
        """Return the complete, independent checkpoint-embeddable vocabulary."""
        self._validate_tokens(self.tokens)
        return {"version": 1, "type": "HybridTokenizer", "tokens": list(self.tokens)}

    @classmethod
    def from_dict(cls, payload):
        """Restore exact token IDs, rejecting malformed or incompatible specs."""
        validate_tokenizer_spec(payload, "HybridTokenizer")
        return cls(payload["tokens"])

    def save(self, path=None):
        return save_json_atomic(DEFAULT_TEXT_VOCAB if path is None else path, self.to_dict())

    @classmethod
    def load(cls, path=None):
        return cls.from_dict(load_json(DEFAULT_TEXT_VOCAB if path is None else path))

    def valid_next_ids(self, ids):
        """Return sorted IDs that keep a prefix valid UTF-8 (for logit masking).

        A leading BOS is accepted; BOS/UNK/PAD are never generated. EOS is only
        permitted between complete characters, and an ended prefix allows no
        next tokens. Invalid prefixes raise ValueError rather than hiding bad
        byte sequences. Overlong encodings, surrogates and >U+10FFFF are excluded.
        """
        remaining, low, high, ended = self._prefix_state(ids)
        if ended:
            return []
        if remaining:
            return [4 + byte for byte in range(low, high + 1)]
        return ([self.eos] + list(range(4, 4 + 0x80))
                + list(range(4 + 0xC2, 4 + 0xF5))
                + list(range(260, len(self.tokens))))

    def pending_byte_count(self, ids):
        """Return continuation bytes still required; invalid prefixes raise ValueError.

        Generation can require this count to fit within its remaining token
        budget after choosing a candidate, avoiding a truncated final character.
        """
        return self._prefix_state(ids)[0]

    def _prefix_state(self, ids):
        remaining, low, high = 0, 0x80, 0xBF
        ended = False
        for position, value in enumerate(ids):
            token_id = self._checked_id(value)
            if ended:
                raise ValueError("tokens after EOS are not a generation prefix")
            if token_id == self.bos and position == 0:
                continue
            if token_id in (self.bos, self.unk, self.pad):
                raise ValueError("unexpected special token in generation prefix")
            if token_id == self.eos or token_id >= 260:
                if remaining:
                    raise ValueError("non-byte token interrupts a UTF-8 sequence")
                ended = token_id == self.eos
                continue
            byte = token_id - 4
            if remaining:
                if not low <= byte <= high:
                    raise ValueError("invalid UTF-8 continuation byte")
                remaining -= 1
                low, high = 0x80, 0xBF
            elif byte < 0x80:
                continue
            elif 0xC2 <= byte <= 0xDF:
                remaining = 1
            elif 0xE0 <= byte <= 0xEF:
                remaining = 2
                low = 0xA0 if byte == 0xE0 else 0x80
                high = 0x9F if byte == 0xED else 0xBF
            elif 0xF0 <= byte <= 0xF4:
                remaining = 3
                low = 0x90 if byte == 0xF0 else 0x80
                high = 0x8F if byte == 0xF4 else 0xBF
            else:
                raise ValueError("invalid UTF-8 leading byte")
        return remaining, low, high, ended
